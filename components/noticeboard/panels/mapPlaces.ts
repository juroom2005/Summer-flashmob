//
// 각 장소 1개 = 리스트 항목 + 지도 마커 + 팝업 카드.
//
// ── 좌표(pin) ────────────────────────────────────────────────────
//   지도 원본 601×455 기준의 백분율(x%, y%). 지도를 어떤 크기로 렌더해도
//   비율이 유지된다. 값은 시안을 보고 추정한 초기값 → 실제 화면에서
//   미세조정할 것(이 파일의 x/y 만 고치면 됨).
//
// ── 시부야역(station) ────────────────────────────────────────────
//   핀이 아니라 지도 우하단 "시부야역" 글자 영역 전체가 호버 영역.
//   kind:"area" + rect(x%,y%,w%,h%) 로 표현. 마커(핀)는 렌더 안 함.
//
// ── 별점(rating) ─────────────────────────────────────────────────
//   0~5 실수. 반별 표현 위해 소수 유지(예: 3.8 → 별 3개 + 반별 0.8→반올림).
//   렌더 쪽에서 채움/반/빈 별을 계산.
// ═══════════════════════════════════════════════════════════════════

